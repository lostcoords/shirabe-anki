import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { Window } from 'happy-dom';

const window = new Window();
const document = window.document;
let now = 10;
let frame;
const replies = [];
const calls = [];
window.__shirabe = { native: true, useCollectionStates: true, cardId: 42 };
const bridge = window.pycmd = (command, callback) => { calls.push(command); replies.push(callback); };
Object.defineProperty(window.performance, 'now', { value: () => now });
window.requestAnimationFrame = (callback) => { frame = callback; return 1; };
window.cancelAnimationFrame = () => { frame = null; };
document.body.innerHTML = '<main id="qa"><span id="word">猫</span></main><div class="sb-host"></div>';
const host = document.querySelector('.sb-host');
const shadow = host.attachShadow({ mode: 'open' });
shadow.innerHTML = '<div class="sb-popup" style="opacity:1;visibility:visible"><div class="sb-body">Loading</div></div>';
const popup = shadow.querySelector('.sb-popup');
window.HTMLElement.prototype.getBoundingClientRect = () => ({ x: 1, y: 1, left: 1, top: 1, right: 101, bottom: 31, width: 100, height: 30 });
await window.eval(await readFile(new URL('template_lookup_probe.js', import.meta.url), 'utf8'));
const probe = window.__shirabeLookupTiming;
const tick = (at) => { now = at; const callback = frame; frame = null; callback(); };
probe.arm('猫', 'cat');
assert.equal(probe.result, null);
now = 20;
document.querySelector('#word').dispatchEvent(new window.MouseEvent('click', { bubbles: true }));
popup.classList.add('sb-visible');
window.pycmd('shirabe:states:猫', () => {});
assert.deepEqual(calls, ['shirabe:states:猫']);
tick(30);
assert.equal(probe.result, null, 'A visible loading shell is not a definition');
popup.innerHTML = '<a class="sb-headword">猫</a><span class="sb-gloss-row">dog</span>';
tick(40);
assert.equal(probe.result, null, 'A different definition must not satisfy the sample');
popup.querySelector('.sb-gloss-row').textContent = 'cat';
host.style.visibility = 'hidden';
tick(50);
assert.equal(probe.result, null, 'A hidden shadow host is not a visible definition');
host.style.visibility = 'visible';
popup.style.opacity = '0';
tick(60);
assert.equal(probe.result, null, 'A transparent definition is not visible');
popup.style.opacity = '1';
tick(70);
assert.equal(probe.result.elapsedMs, 50);
assert.equal(probe.result.headword, '猫');
assert.equal(probe.result.gloss, 'cat');
assert.equal(probe.result.collectionStates.length, 1);
assert.equal(probe.result.collectionStates[0].completed, false, 'Definition is recorded before the native reply');
now = 100;
replies[0]('{"猫":"new"}');
assert.equal(probe.result.elapsedMs, 50, 'Later replies cannot extend the first-definition timestamp');
assert.equal(probe.result.collectionStates[0].elapsedMs, 80);
assert.equal(probe.result.collectionStates[0].states['猫'], 'new');
assert.equal(probe.result.collectionStates[0].completed, true);
assert.throws(() => probe.arm('猫', 'cat'), /Dismiss/);
popup.classList.remove('sb-visible');
probe.arm('猫', 'cat');
assert.equal(probe.result, null, 'Arming must not reuse the last sample');
probe.dispose();
assert.equal(window.pycmd, bridge, 'The real native bridge is restored');
await window.happyDOM.close();
console.log('visible definition and native callback timing verified');
